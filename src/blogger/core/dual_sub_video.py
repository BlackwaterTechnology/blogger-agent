def generate_dual_subtitle_video(
    input_path: str | Path,
    output_mp4: str | Path,
    voice: str = "en-US-JennyNeural",
    rate: Optional[str] = None,
    pitch: str = "+2Hz",
    title: str = "English Listening Practice",
    tag: Optional[str] = None,
    cover_path: Optional[str | Path] = None,
    subtitle: Optional[str] = None,
    bg_image: Optional[str | Path] = None,
    level: str = "a2",
    bg_blur: Optional[int] = None,
    bg_alpha: Optional[float] = None,
    layout: str = "standard",
    avatar_image: Optional[str | Path] = None,
    avatar_badge: str = "AI TECH MENTOR",
    avatar_video: Optional[str | Path] = None,
    avatar_driver: Optional[str] = None,
    generate_digital_human: bool = False,
) -> str:
    """High-level end-to-end generator pipeline: input text -> Edge-TTS speech & cues -> rendered MP4."""
    input_p = Path(input_path).resolve()
    if not input_p.exists():
        raise FileNotFoundError(f"Input file '{input_p}' does not exist.")

    cfg = resolve_level_preset(level=level, rate=rate, tag=tag, subtitle=subtitle)
    actual_rate = cfg["rate"]
    actual_tag = cfg["tag"]
    actual_sub = cfg["subtitle"]

    temp_dir = tempfile.mkdtemp(prefix="tts_sub_")
    try:
        mp3_path = os.path.join(temp_dir, "speech.mp3")
        vtt_path = os.path.join(temp_dir, "speech.vtt")

        actual_voice = resolve_voice(voice)
        logger.info(f"Synthesizing speech ({cfg['level'].upper()} rate={actual_rate}) and timestamps using {actual_voice}...")
        tts_cmd = [
            sys.executable,
            "-m",
            "edge_tts",
            f"--voice={actual_voice}",
            f"--rate={actual_rate}",
            f"--pitch={pitch}",
            "-f",
            str(input_p),
            "--write-media",
            mp3_path,
            "--write-subtitles",
            vtt_path,
        ]
        res = subprocess.run(tts_cmd, capture_output=True, text=True)
        if res.returncode != 0:
            raise RuntimeError(f"Edge-TTS failed: {res.stderr}")

        cues = parse_vtt(vtt_path)
        logger.info(f"Parsed {len(cues)} sentence cues from {vtt_path}")

        # Scheme B: Resolve or generate Digital Human talking head video
        talking_avatar_video: Optional[Path] = None
        if avatar_video:
            av_vid_p = Path(avatar_video).resolve()
            if av_vid_p.exists():
                talking_avatar_video = av_vid_p
                logger.info(f"Using provided digital human video: {talking_avatar_video}")
        elif (generate_digital_human or avatar_driver) and (layout or "").lower() == "avatar":
            resolved_av = resolve_avatar_image(avatar_image)
            if resolved_av and resolved_av.exists():
                from src.blogger.core.digital_human import get_digital_human_driver
                driver = get_digital_human_driver(avatar_driver)
                temp_talking_mp4 = Path(temp_dir) / "avatar_talking.mp4"
                logger.info(f"Generating Scheme B digital human talking avatar with {driver.name}...")
                talking_avatar_video = driver.generate(
                    source_image=resolved_av,
                    driving_audio=mp3_path,
                    output_video=temp_talking_mp4,
                )

        rendered_mp4 = render_video(
            cues,
            mp3_path,
            output_mp4,
            title=title,
            tag=actual_tag,
            bg_image_path=bg_image,
            bg_blur=bg_blur,
            bg_alpha=bg_alpha,
            layout=layout,
            avatar_image=avatar_image,
            avatar_badge=avatar_badge,
            avatar_video=talking_avatar_video,
        )

        if cover_path:
            generate_video_cover(
                cover_path,
                title=title,
                tag=actual_tag,
                subtitle=actual_sub,
                bg_image_path=bg_image,
                bg_blur=bg_blur,
                bg_alpha=bg_alpha,
                layout=layout,
                avatar_image=avatar_image,
                avatar_badge=avatar_badge,
                avatar_video=talking_avatar_video,
            )

        return rendered_mp4
    finally:
        shutil.rmtree(temp_dir, ignore_errors=True)


def clean_video_title(title: str) -> str:
    """Ensure title has 0 emoji or prohibited symbols for WeChat Video compliance."""
    emoji_pattern = re.compile(r"[\U00010000-\U0010ffff]", flags=re.UNICODE)
    cleaned = emoji_pattern.sub("", title)
    cleaned = re.sub(r"[🇯🇵🎯⭐💡💯🔥🚀📌🎉✨]+", "", cleaned)
    cleaned = re.sub(r"\s+", " ", cleaned).strip()
    return cleaned


def clean_video_desc(desc: str, default_title: str = "", level: str = "a2") -> str:
    """Ensure description length is strictly between 60 and 120 characters in English."""
    desc = desc.strip()
    preset = CEFR_LEVEL_PRESETS.get(level.lower(), CEFR_LEVEL_PRESETS["a2"])
    if len(desc) < 60:
        if default_title and len(desc) < 20:
            desc = f"Master English listening with {default_title}, featuring {preset['desc_level']} dual-tier subtitles."
        else:
            padding = f" Featuring dual-tier subtitles and {preset['desc_level']} context stream for immersion."
            desc = (desc + padding).strip()
            if len(desc) < 60:
                desc = (desc + " Ideal for daily shadowing drills.").strip()
    if len(desc) > 120:
        desc = desc[:118].rstrip("，。；！？,.!?; ") + "."
    return desc


