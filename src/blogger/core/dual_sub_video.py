def parse_time(t_str: str) -> float:
    """Parse WebVTT timestamp (HH:MM:SS.mmm or MM:SS.mmm) into seconds."""
    t_str = t_str.replace(",", ".")
    parts = t_str.split(":")
    if len(parts) == 3:
        h, m, s = float(parts[0]), float(parts[1]), float(parts[2])
        return h * 3600 + m * 60 + s
    elif len(parts) == 2:
        m, s = float(parts[0]), float(parts[1])
        return m * 60 + s
    return float(parts[0])


def parse_vtt(vtt_path: str | Path) -> List[Dict[str, Any]]:
    """Parse a WebVTT file generated by Edge-TTS into structured cues."""
    with open(vtt_path, "r", encoding="utf-8") as f:
        content = f.read()

    blocks = content.strip().split("\n\n")
    cues: List[Dict[str, Any]] = []
    time_pattern = re.compile(
        r"(\d{2}:\d{2}:\d{2}[,\.]\d{3}|\d{2}:\d{2}[,\.]\d{3})\s*-->\s*(\d{2}:\d{2}:\d{2}[,\.]\d{3}|\d{2}:\d{2}[,\.]\d{3})"
    )

    for b in blocks:
        lines = b.strip().split("\n")
        for i, line in enumerate(lines):
            m = time_pattern.search(line)
            if m:
                start = parse_time(m.group(1))
                end = parse_time(m.group(2))
                text = " ".join([l.strip() for l in lines[i + 1 :] if l.strip()])
                if text:
                    cues.append({"start": start, "end": end, "text": text})
                break
    return cues


def wrap_text(text: str, font: ImageFont.ImageFont, max_width: int, draw: ImageDraw.ImageDraw) -> List[str]:
    """Wrap text to fit within a given pixel width."""
    words = text.split()
    lines: List[str] = []
    current_line: List[str] = []
    for word in words:
        test_line = " ".join(current_line + [word])
        bbox = draw.textbbox((0, 0), test_line, font=font)
        w = bbox[2] - bbox[0]
        if w <= max_width:
            current_line.append(word)
        else:
            if current_line:
                lines.append(" ".join(current_line))
            current_line = [word]
    if current_line:
        lines.append(" ".join(current_line))
    return lines


def create_gradient_bg(
    width: int, height: int, top_hex: str = "#0B132B", bottom_hex: str = "#1C2541"
) -> Image.Image:
    """Create a high-contrast vertical linear gradient background image."""
    img = Image.new("RGB", (width, height), top_hex)
    draw = ImageDraw.Draw(img)
    r1, g1, b1 = tuple(int(top_hex.lstrip("#")[i : i + 2], 16) for i in (0, 2, 4))
    r2, g2, b2 = tuple(int(bottom_hex.lstrip("#")[i : i + 2], 16) for i in (0, 2, 4))
    for y in range(height):
        ratio = y / height
        r = int(r1 + (r2 - r1) * ratio)
        g = int(g1 + (g2 - g1) * ratio)
        b = int(b1 + (b2 - b1) * ratio)
        draw.line([(0, y), (width, y)], fill=(r, g, b))
    return img


def prepare_ambient_background(
    width: int = 1920,
    height: int = 1080,
    bg_image_path: Optional[str | Path] = None,
    blur_radius: int = 3,
    overlay_color: str = "#0B132B",
    overlay_alpha: float = 0.20,
) -> Image.Image:
    """Prepare an ambient background image with aspect-fill cropping, subtle micro-blur, and dark scrim.

    Falls back to a linear gradient if bg_image_path is not provided or cannot be loaded.
    """
    if bg_image_path:
        p = Path(bg_image_path).resolve()
        if p.exists() and p.is_file():
            try:
                img = Image.open(p).convert("RGB")
                orig_w, orig_h = img.size
                if orig_w > 0 and orig_h > 0:
                    scale = max(width / orig_w, height / orig_h)
                    new_w = int(orig_w * scale)
                    new_h = int(orig_h * scale)
                    resample_filter = getattr(Image.Resampling, "LANCZOS", Image.LANCZOS)
                    img = img.resize((new_w, new_h), resample_filter)

                    left = max(0, (new_w - width) // 2)
                    top = max(0, (new_h - height) // 2)
                    img = img.crop((left, top, left + width, top + height))

                    if blur_radius > 0:
                        img = img.filter(ImageFilter.GaussianBlur(radius=blur_radius))

                    overlay = Image.new("RGB", (width, height), overlay_color)
                    img = Image.blend(img, overlay, overlay_alpha)
                    return img
            except Exception as e:
                logger.warning(f"Failed to process ambient background image from {p}: {e}. Falling back to gradient.")

    return create_gradient_bg(width, height)


def apply_top_scrim(
    img: Image.Image,
    height: int = 150,
    start_alpha: float = 0.75,
    overlay_color: tuple[int, int, int] = (11, 19, 43),
) -> Image.Image:
    """Apply a subtle top dark-gradient scrim to guarantee header text contrast against light backgrounds."""
    overlay = Image.new("RGBA", img.size, (0, 0, 0, 0))
    draw_ov = ImageDraw.Draw(overlay)
    r, g, b = overlay_color
    for y in range(height):
        alpha = int(255 * start_alpha * (1.0 - (y / height) ** 1.5))
        draw_ov.line([(0, y), (img.width, y)], fill=(r, g, b, alpha))
    return Image.alpha_composite(img.convert("RGBA"), overlay).convert("RGB")


