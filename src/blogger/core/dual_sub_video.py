def generate_video_payload_md(
    payload_dir: str | Path,
    title: str,
    desc: str,
    collection: str = "软件教程",
    author: str = "Blogger Agent",
    video_filename: str = "video.mp4",
    cover_filename: str = "cover.png",
    sentences_path: Optional[str | Path] = None,
    notes: Optional[str] = None,
    level: str = "a2",
    layout: str = "standard",
    avatar_filename: Optional[str] = None,
    avatar_video_filename: Optional[str] = None,
) -> Path:
    """Generate a standard payload.md compliant with publish-video and video platform specifications."""
    p_dir = Path(payload_dir).resolve()
    p_dir.mkdir(parents=True, exist_ok=True)
    out_md = p_dir / "payload.md"

    clean_t = clean_video_title(title)
    clean_d = clean_video_desc(desc, default_title=clean_t, level=level)

    # Validate collection
    allowed = []
    try:
        from ..config import get_wechat_collections
        allowed = get_wechat_collections(content_type="video")
    except Exception:
        try:
            from blogger.config import get_wechat_collections
            allowed = get_wechat_collections(content_type="video")
        except Exception:
            allowed = ["软件教程", "程序员", "agent", "claude code"]

    if allowed and collection not in allowed:
        logger.warning(f"Collection '{collection}' not in allowed video collections {allowed}. Defaulting to '{allowed[0]}'")
        collection = allowed[0]

    transcript_lines = []
    if sentences_path and Path(sentences_path).exists():
        with open(sentences_path, "r", encoding="utf-8") as f:
            for line in f:
                stripped = line.strip()
                if stripped:
                    transcript_lines.append(stripped)

    md_lines = [
        "---",
        f'title: "{clean_t}"',
        f'author: "{author}"',
        f'desc: "{clean_d}"',
        f'level: "{level.lower()}"',
        f'layout: "{layout.lower()}"',
        f'collection: "{collection}"',
        f'cover: "{cover_filename}"',
        f'video: "{video_filename}"',
    ]
    if avatar_filename:
        md_lines.append(f'avatar: "{avatar_filename}"')
    if avatar_video_filename:
        md_lines.append(f'avatar_video: "{avatar_video_filename}"')
    md_lines.extend([
        "---",
        "",
        f"# {clean_t}",
        "",
        "## Overview & Learning Objectives",
        "",
        clean_d,
        "",
    ])

    if notes:
        md_lines.extend([
            "## Key Vocabulary & Notes",
            "",
            notes.strip(),
            "",
        ])

    if transcript_lines:
        md_lines.extend([
            "## Sentence-by-Sentence Transcript",
            "",
        ])
        for idx, sentence in enumerate(transcript_lines, start=1):
            md_lines.append(f"{idx}. {sentence}")
        md_lines.append("")

    content = "\n".join(md_lines)
    out_md.write_text(content, encoding="utf-8")
    logger.info(f"Video payload.md generated at: {out_md}")
    return out_md


def create_dual_sub_payload(
    payload_dir: str | Path,
    sentences_path: str | Path,
    title: str,
    desc: str,
    collection: str = "软件教程",
    voice: str = "en-US-JennyNeural",
    rate: Optional[str] = None,
    pitch: str = "+2Hz",
    tag: Optional[str] = None,
    subtitle: Optional[str] = None,
    author: str = "Blogger Agent",
    notes: Optional[str] = None,
    bg_image: Optional[str | Path] = None,
    level: str = "a2",
    bg_blur: Optional[int] = None,
    bg_alpha: Optional[float] = None,
    layout: str = "standard",
    avatar_image: Optional[str | Path] = None,
    avatar_badge: str = "AI TECH MENTOR",
    avatar_video: Optional[str | Path] = None,
    avatar_driver: Optional[str] = None,
    generate_digital_human: bool = False,
) -> Dict[str, Any]:
    """Assemble a complete standard video payload: video.mp4, cover.png, payload.md, sentences.txt."""
    p_dir = Path(payload_dir).resolve()
    p_dir.mkdir(parents=True, exist_ok=True)

    sent_p = Path(sentences_path).resolve()
    if not sent_p.exists():
        raise FileNotFoundError(f"Sentences file not found: {sent_p}")

    dest_sent = p_dir / "sentences.txt"
    if sent_p != dest_sent:
        shutil.copy2(sent_p, dest_sent)

    cfg = resolve_level_preset(level=level, rate=rate, tag=tag, subtitle=subtitle)

    # Resolve ambient background image
    actual_bg: Optional[Path] = None
    if bg_image:
        bg_src = Path(bg_image).resolve()
        if bg_src.exists():
            dest_bg = p_dir / "bg.png"
            if bg_src != dest_bg:
                shutil.copy2(bg_src, dest_bg)
            actual_bg = dest_bg
        else:
            logger.warning(f"Specified bg_image '{bg_image}' not found.")

    if not actual_bg:
        for candidate in [p_dir / "bg.png", p_dir / "background.png"]:
            if candidate.exists():
                actual_bg = candidate
                break

    # Resolve avatar if avatar layout requested
    actual_avatar: Optional[Path] = None
    avatar_filename: Optional[str] = None
    actual_avatar_video: Optional[Path] = None
    avatar_video_filename: Optional[str] = None

    is_avatar = (layout or "").lower() == "avatar"
    if is_avatar:
        resolved_av = resolve_avatar_image(avatar_image)
        if resolved_av and resolved_av.exists():
            dest_av = p_dir / "avatar.png"
            if resolved_av != dest_av:
                shutil.copy2(resolved_av, dest_av)
            actual_avatar = dest_av
            avatar_filename = "avatar.png"

            # Copy all available avatar animation states into payload directory
            source_states = resolve_avatar_states(resolved_av)
            for st_name, st_path in source_states.items():
                if st_name == "closed":
                    continue
                if st_name == "open":
                    dest_st = p_dir / "avatar_mouth_open.png"
                elif st_name == "wide":
                    dest_st = p_dir / "avatar_mouth_wide.png"
                elif st_name == "blink":
                    dest_st = p_dir / "avatar_blink.png"
                else:
                    dest_st = p_dir / f"avatar_{st_name}.png"
                if st_path.exists() and st_path != dest_st:
                    shutil.copy2(st_path, dest_st)
        else:
            logger.warning(f"Avatar layout requested but avatar could not be resolved.")
            is_avatar = False
            layout = "standard"

        if avatar_video:
            src_av_vid = Path(avatar_video).resolve()
            if src_av_vid.exists():
                dest_av_vid = p_dir / "avatar_talking.mp4"
                if src_av_vid != dest_av_vid:
                    shutil.copy2(src_av_vid, dest_av_vid)
                actual_avatar_video = dest_av_vid
                avatar_video_filename = "avatar_talking.mp4"

    video_path = p_dir / "video.mp4"
    cover_path = p_dir / "cover.png"

    # 1. Generate video
    generate_dual_subtitle_video(
        input_path=dest_sent,
        output_mp4=video_path,
        voice=voice,
        rate=cfg["rate"],
        pitch=pitch,
        title=title,
        tag=cfg["tag"],
        bg_image=actual_bg,
        level=cfg["level"],
        bg_blur=bg_blur,
        bg_alpha=bg_alpha,
        layout=layout,
        avatar_image=actual_avatar,
        avatar_badge=avatar_badge,
        avatar_video=actual_avatar_video,
        avatar_driver=avatar_driver,
        generate_digital_human=generate_digital_human,
    )

    # If digital human video was generated during pipeline, record it
    dest_talking = p_dir / "avatar_talking.mp4"
    if dest_talking.exists():
        actual_avatar_video = dest_talking
        avatar_video_filename = "avatar_talking.mp4"

    # 2. Generate cover
    generate_video_cover(
        output_path=cover_path,
        title=title,
        tag=cfg["tag"],
        subtitle=cfg["subtitle"],
        bg_image_path=actual_bg,
        bg_blur=bg_blur,
        bg_alpha=bg_alpha,
        layout=layout,
        avatar_image=actual_avatar,
        avatar_badge=avatar_badge,
        avatar_video=actual_avatar_video,
    )

    # 3. Generate payload.md
    payload_md = generate_video_payload_md(
        payload_dir=p_dir,
        title=title,
        desc=desc,
        collection=collection,
        author=author,
        video_filename="video.mp4",
        cover_filename="cover.png",
        sentences_path=dest_sent,
        notes=notes,
        level=cfg["level"],
        layout=layout,
        avatar_filename=avatar_filename,
        avatar_video_filename=avatar_video_filename,
    )

    return {
        "payload_dir": p_dir,
        "payload_md": payload_md,
        "video_path": video_path,
        "cover_path": cover_path,
        "sentences_path": dest_sent,
        "bg_image": str(actual_bg) if actual_bg else None,
        "avatar_image": str(actual_avatar) if actual_avatar else None,
        "avatar_video": str(actual_avatar_video) if actual_avatar_video else None,
        "layout": layout,
        "level": cfg["level"],
        "rate": cfg["rate"],
        "tag": cfg["tag"],
        "title": clean_video_title(title),
        "desc": clean_video_desc(desc, title, level=cfg["level"]),
        "collection": collection,
    }
